"""Resolve installed distributions to PyPI-verified, hash-locked requirements.

Run only after intentional dependency selection and pip check. All published wheel
hashes support the same pinned versions across Windows and Linux. No credentials.
"""

import concurrent.futures
import importlib.metadata
import json
import urllib.request
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

ROOT = Path(__file__).resolve().parents[1]
RUNTIME = [
    "fastapi",
    "uvicorn",
    "sqlalchemy",
    "psycopg",
    "psycopg-binary",
    "alembic",
    "pydantic-settings",
    "jinja2",
    "argon2-cffi",
    "python-multipart",
    "httpx",
    "pyyaml",
    "tzdata",
]


def closure(names: list[str]) -> set[str]:
    found: set[str] = set()
    pending = list(names)
    while pending:
        name = canonicalize_name(pending.pop())
        if name in found:
            continue
        found.add(name)
        for raw in importlib.metadata.requires(name) or []:
            req = Requirement(raw)
            if not req.marker or req.marker.evaluate():
                pending.append(req.name)
    return found


def entry(name: str) -> str:
    version = importlib.metadata.version(name)
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=30) as response:  # nosec B310 - fixed HTTPS PyPI
        data = json.load(response)
    hashes = sorted({f["digests"]["sha256"] for f in data["urls"] if not f["yanked"]})
    if not hashes:
        raise RuntimeError(f"No eligible published archives for {name}")
    return f"{name}=={version} \\\n" + " \\\n".join(f"    --hash=sha256:{h}" for h in hashes) + "\n"


def main() -> None:
    runtime = closure(RUNTIME)
    development = {
        canonicalize_name(d.metadata["Name"]) for d in importlib.metadata.distributions()
    }
    development -= {"pip", "setuptools", "aegis-security-lab"}
    with concurrent.futures.ThreadPoolExecutor(max_workers=8) as executor:
        entries = dict(
            zip(
                sorted(development | runtime),
                executor.map(entry, sorted(development | runtime)),
                strict=True,
            )
        )
    for filename, names in (
        ("requirements.lock", runtime),
        ("requirements-dev.lock", development | runtime),
    ):
        (ROOT / filename).write_text(
            "# Pinned versions and PyPI SHA-256 archive hashes; generated by scripts.refresh_locks\n"
            + "".join(entries[n] for n in sorted(names)),
            encoding="utf-8",
        )
        print(f"{filename}: {len(names)} pinned distributions")


if __name__ == "__main__":
    main()
